package no_5339;
/*
문제-5339 (브론즈5): 콜센터
- 예제 출력과 동일한 ASCII 아트를 출력하는 문제
- 두 '|' 사이에는 공백 10개

주요 포인트
- '\' 출력 시 이스케이프 처리 필요 (\\)
*/
public class No5339 {
    public static void main(String[] args) {
        System.out.println("     /~\\");
        System.out.println("    ( oo|");
        System.out.println("    _\\=/_");
        System.out.println("   /  _  \\");
        System.out.println("  //|/.\\|\\\\");
        System.out.println(" ||  \\ /  ||");
        System.out.println("============");
        System.out.println("|          |");
        System.out.println("|          |");
        System.out.println("|          |");
    }
}

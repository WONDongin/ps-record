package level1;
/*
문제: 2016년

문제 요약
- 2016년 1월 1일은 금요일(FRI)이다.
- 입력받은 a월 b일이 무슨 요일인지 반환하는 문제이다.
- 2016년은 윤년이므로 2월은 29일까지 존재한다.

접근 방법
- 각 달의 일수를 배열에 저장한다.
- 입력받은 달 이전까지의 총 일수를 모두 더한다.
- 현재 날짜(b)를 더해 1월 1일부터 며칠이 지났는지 계산한다.
- 요일 배열에서 (총 일수 - 1) % 7 인덱스를 이용해 정답을 찾는다.

핵심 아이디어
- 2016년 1월 1일이 금요일이므로 요일 배열을 FRI부터 시작한다.
- 특정 날짜의 요일은 1월 1일 기준으로 경과한 일 수를 7로 나눈 나머지로 계산할 수 있다.

주의할 점
- 2016년은 윤년이므로 2월이 29일이다.
- 배열 인덱스는 0부터 시작하므로 (total - 1) % 7을 사용해야 한다.

배운 점
- 날짜 계산 문제는 기준 날짜를 잡고 누적 일수를 계산하면 쉽게 해결할 수 있다.
- 주기성이 있는 데이터는 나머지 연산(%)을 활용하면 효율적으로 처리할 수 있다.
*/
public class No52 {
    class Solution {
        public String solution(int a, int b) {

            int[] days = {
                    31, 29, 31, 30, 31, 30,
                    31, 31, 30, 31, 30, 31
            };

            String[] week = {
                    "FRI", "SAT", "SUN",
                    "MON", "TUE", "WED", "THU"
            };

            int total = b;

            for(int i = 0; i < a - 1; i++){
                total += days[i];
            }

            return week[(total - 1) % 7];
        }
    }
}

package level0;
/*
문제: 아이스 아메리카노

로직
- 가지고 있는 돈을 5,500으로 나누어 최대 구매 가능한 잔 수를 구한다.
- 5,500으로 나눈 나머지를 남는 돈으로 구한다.
- 결과를 배열에 담아 반환한다.

핵심 구현
- 핵심 코드
  ex)
  new int[]{money / 5500, money % 5500};

- 핵심 코드 설명
  몫(/) 연산으로 구매 가능한 잔 수를 구하고, 나머지(%) 연산으로 남는 금액을 계산하여 배열로 반환한다.

포인트
- 몫 연산은 최대 구매 개수를 구할 때 사용한다.
- 나머지 연산은 남는 금액을 구할 때 사용한다.
- 별도의 반복문 없이 한 줄로 해결할 수 있다.

회고
- 몫과 나머지 연산만으로 간단하게 문제를 해결할 수 있었고, 배열을 바로 생성하여 반환하는 방법도 익힐 수 있었다.
*/
public class No39 {
    class Solution {
        public int[] solution(int money) {
            return new int[]{money / 5500, money % 5500};
        }
    }
}

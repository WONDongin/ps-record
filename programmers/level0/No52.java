package level0;
/*
문제: 순서쌍의 개수

로직
- 1부터 n까지 반복하면서 n의 약수인지 확인한다.
- 약수인 경우 개수를 증가시킨다.
- 최종 약수의 개수를 반환한다.

핵심 구현
- if (n % i == 0)
- 나머지가 0이면 i는 n의 약수이므로 count를 증가시킨다.

포인트
- 순서쌍의 개수는 n의 약수의 개수와 같다.
- 1부터 n까지 순회하며 약수를 모두 찾는 방식으로 해결할 수 있다.
- 나머지 연산(%)을 이용해 약수 여부를 간단하게 판별할 수 있다.

회고
- 순서쌍 문제는 결국 약수의 개수를 구하는 문제로 변환할 수 있다는 점을 배웠다.
- 반복문과 나머지 연산만으로도 기본적인 약수 탐색 문제를 해결할 수 있었다.
*/
public class No52 {
    public static void main(String[] args) {
        int n = 100;
        int count = 0;

        for(int i = 1; i <= n; i++){
            if(n % i == 0){
                count++;
            }
        }

        System.out.println(count);
    }
}

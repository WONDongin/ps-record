package level0;
/*
문제: 세균 증식

로직
- 세균은 1시간마다 2배씩 증가한다.
- t시간 후의 세균 수는 n × 2^t와 같다.
- 비트 연산(<<)을 이용해 결과를 반환한다.

핵심 구현
- 핵심 코드
  return n << t;

- 핵심 코드 설명
  - 왼쪽 시프트(<<) 연산은 2를 곱하는 효과가 있다.
  - n을 t번 왼쪽으로 이동하면 n × 2^t가 된다.

포인트
- 2의 거듭제곱 계산은 비트 연산으로 간단하게 구현할 수 있다.
- 반복문이나 Math.pow()를 사용할 필요가 없다.

회고
- 비트 연산은 2의 거듭제곱을 계산할 때 매우 효율적이다.
- 시프트 연산의 의미를 이해하면 다양한 코딩 테스트 문제에서 활용할 수 있다.
*/
public class No70 {
    class Solution {
        public int solution(int n, int t) {
            return n << t;
        }
    }
}

package level0;
/*
문제: 종이 자르기

로직
- M × N 크기의 종이를 모두 1 × 1 크기로 자르면 총 M × N개의 조각이 만들어진다.
- 한 번 가위질할 때마다 종이 조각의 개수는 하나씩 증가한다.
- 처음에는 종이가 한 장이므로 M × N개의 조각을 만들려면 M × N - 1번 잘라야 한다.

핵심 구현
- 전체 종이 조각의 개수인 M * N에서 1을 뺀 값을 반환한다.

포인트
- 종이를 겹쳐서 자를 수 없으므로 한 번 자를 때마다 조각은 하나만 증가한다.
- 가로와 세로를 따로 계산하지 않고 전체 조각의 개수를 이용하면 간단하게 해결할 수 있다.
- 1 × 1 크기의 종이는 이미 완성된 상태이므로 0을 반환한다.

회고
- 자르는 방향을 나누어 계산하기보다 조각의 개수가 증가하는 규칙을 이용해 간단하게 해결했다.
*/
public class No205 {
    class Solution {
        public int solution(int M, int N) {
            return M * N - 1;
        }
    }
}

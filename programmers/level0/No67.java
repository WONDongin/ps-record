package level0;
/*
문제: 자릿수 더하기

로직
- n이 0보다 큰 동안 반복한다.
- n % 10으로 마지막 자릿수를 구해 answer에 더한다.
- n /= 10으로 마지막 자릿수를 제거한다.
- 모든 자릿수를 더한 결과를 반환한다.

핵심 구현
- 핵심 코드
  while (n > 0) {
      answer += n % 10;
      n /= 10;
  }

- 핵심 코드 설명
  - n % 10은 현재 숫자의 마지막 자릿수를 구한다.
  - n /= 10은 마지막 자릿수를 제거하여 다음 자릿수를 확인한다.

포인트
- 나머지 연산(%)과 나눗셈(/)만으로 각 자릿수를 쉽게 구할 수 있다.
- 문자열 변환 없이 정수 연산만으로 해결할 수 있다.

회고
- 자릿수 관련 문제에서 자주 사용하는 기본 패턴을 다시 익힐 수 있었다.
- 문자열로 변환하는 방법보다 메모리 사용이 적고 연산도 간단하게 구현할 수 있었다.
*/
public class No67 {
    class Solution {
        public int solution(int n) {
            int answer = 0;

            while (n > 0) {
                answer += n % 10;
                n /= 10;
            }

            return answer;
        }
    }
}

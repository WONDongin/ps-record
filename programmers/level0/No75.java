package level0;
/*
문제: n의 배수

로직
- num을 n으로 나눈 나머지를 확인한다.
- 나머지가 0이면 n의 배수이므로 1을 반환한다.
- 그렇지 않으면 0을 반환한다.

핵심 구현
- 핵심 코드
  ex) return num % n == 0 ? 1 : 0;

- 핵심 코드 설명
  - % 연산자는 나머지를 구하는 연산자이다.
  - 나머지가 0이면 num이 n으로 나누어떨어진다는 의미이므로 n의 배수이다.
  - 삼항 연산자를 사용해 조건에 따라 1 또는 0을 간결하게 반환한다.

포인트
- 배수 판별은 나머지 연산(%)으로 확인한다.
- 조건이 단순하므로 삼항 연산자를 사용하면 코드를 간결하게 작성할 수 있다.
- if-else로도 동일하게 구현 가능하다.

회고
- 배수 판별의 기본 원리인 나머지 연산을 다시 확인할 수 있었다.
- 간단한 조건문에서는 삼항 연산자가 가독성과 코드 길이 측면에서 유용하다는 것을 배웠다.
*/
public class No75 {
    class Solution {
        public int solution(int num, int n) {
            return num % n == 0 ? 1 : 0;
        }
    }
}

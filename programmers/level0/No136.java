package level0;
/*
문제: 조건에 맞게 수열 변환하기 1

로직
- 배열을 순회하며 값의 범위와 홀짝 여부를 확인한다.
- 50 이상인 짝수는 2로 나누고, 50 미만인 홀수는 2를 곱한다.
- 조건에 해당하지 않는 값은 그대로 유지한다.

핵심 구현
- 논리 연산자 &&를 사용해 범위와 홀짝 조건을 함께 검사했다.
- 별도의 배열을 생성하지 않고 기존 배열을 직접 수정했다.

포인트
- 시간 복잡도: O(n)
- 공간 복잡도: O(1)
- 최대 1,000,000개의 원소를 한 번만 순회하도록 구현했다.

회고
- 조건을 명확하게 분리하여 코드의 가독성을 높였다.
- 불필요한 배열 생성을 줄여 메모리를 효율적으로 사용할 수 있었다.
*/
public class No136 {
    class Solution {
        public int[] solution(int[] arr) {
            for (int i = 0; i < arr.length; i++) {
                if (arr[i] >= 50 && arr[i] % 2 == 0) {
                    arr[i] /= 2;
                } else if (arr[i] < 50 && arr[i] % 2 != 0) {
                    arr[i] *= 2;
                }
            }

            return arr;
        }
    }
}

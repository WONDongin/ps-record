package level0;
/*
문제: 피자 나눠 먹기 (1)

로직
- 피자는 한 판당 7조각이다.
- 모든 사람이 한 조각 이상 먹을 수 있도록 필요한 피자 수를 계산한다.
- (n + 6) / 7 공식을 사용해 정수 나눗셈으로 올림 효과를 구현한다.

핵심 구현
- 핵심 코드
  int answer = (n + 6) / 7;
- 7로 나눌 때 필요한 피자 개수를 올림 계산하기 위해
  (값 + 나누는 수 - 1) / 나누는 수 공식을 사용했다.

포인트
- Math.ceil() 없이 정수 연산만으로 올림 계산이 가능하다.
- 정수 올림 공식 (a + b - 1) / b 는 코딩테스트에서 자주 활용되는 패턴이다.

회고
- 처음에는 조건문으로 나머지를 확인하려 했지만,
  정수 올림 공식을 사용하면 한 줄로 더 간결하게 구현할 수 있다는 점을 배웠다.
*/
public class No45 {
    public static void main(String[] args) {
        int n = 15;

        System.out.println((n + 6) / 7);
    }
}

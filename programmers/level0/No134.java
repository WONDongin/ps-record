package level0;
/*
문제: 겹치는 선분의 길이

로직
- 각 선분을 길이 1의 구간으로 나눈다.
- 각 구간을 몇 개의 선분이 지나가는지 배열에 기록한다.
- 두 개 이상의 선분이 지나가는 구간의 개수를 계산한다.
- 계산한 구간의 개수를 겹치는 총길이로 반환한다.

핵심 구현
- 선분의 시작점부터 끝점 직전까지 반복한다.
- 음수 좌표를 배열 인덱스로 사용하기 위해 100을 더한다.
- overlap[i + 100]에 해당 구간을 지나는 선분의 개수를 저장한다.
- count >= 2인 구간의 개수를 answer에 더한다.

포인트
- 선분 [0, 2]는 [0, 1], [1, 2]라는 두 개의 단위 구간으로 처리한다.
- 끝점까지 포함하면 실제 선분의 길이보다 1 크게 계산되므로
  i < line[1] 조건을 사용해야 한다.
- 세 선분이 동시에 겹치는 구간도 한 번만 길이에 포함해야 한다.
- 좌표의 범위가 작기 때문에 배열을 이용한 완전 탐색이 가능하다.

회고
- 선분을 길이 1의 구간으로 나누어 각 구간의 중복 횟수를 기록하면
  복잡한 구간 계산 없이 겹치는 길이를 구할 수 있었다.
*/
public class No134 {
    class Solution {
        public int solution(int[][] lines) {
            int[] overlap = new int[200];
            int answer = 0;

            for (int[] line : lines) {
                for (int i = line[0]; i < line[1]; i++) {
                    overlap[i + 100]++;
                }
            }

            for (int count : overlap) {
                if (count >= 2) {
                    answer++;
                }
            }

            return answer;
        }
    }
}

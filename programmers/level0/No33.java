package level0;
/*
문제: 자릿수 더하기

문제 요약

* 자연수 N이 주어진다
* N의 각 자릿수를 모두 더한 값을 반환한다
* 예를 들어 123이면 1 + 2 + 3 = 6을 반환한다

접근 방법

* answer를 0으로 초기화한다
* n % 10으로 마지막 자릿수를 구한다
* 구한 자릿수를 answer에 누적한다
* n / 10으로 마지막 자릿수를 제거한다
* n이 0이 될 때까지 반복한다

핵심 아이디어

* % 10은 현재 숫자의 마지막 자릿수를 구할 수 있다
* / 10은 현재 숫자의 마지막 자릿수를 제거할 수 있다
* 모든 자릿수를 순회하면서 합계를 누적하면 된다

주의할 점

* n이 0이 되면 모든 자릿수 처리가 완료된 상태이다
* 문제 조건상 자연수가 주어지므로 별도의 예외 처리는 필요 없다
* 문자열 변환 없이 숫자 연산만으로 해결할 수 있다

배운 점

* % 연산을 활용하면 자릿수를 쉽게 분리할 수 있다
* / 연산을 활용하면 사용한 자릿수를 제거할 수 있다
* 자릿수 관련 문제에서 자주 사용하는 기본 패턴을 익힐 수 있었다
*/
public class No33 {
    public static void main(String[] args) {
        int n = 987;
        int answer = 0;

        while (n > 0){
            answer += n % 10; // 마지막 자리 추출
            n /= 10;       // 마지막 자리 제거
        }

        System.out.println(answer);
    }
}

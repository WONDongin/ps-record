package level2;
/*
문제: 피보나치 수

문제 요약
- 피보나치 수열의 n번째 값을 구한다.
- 결과값이 매우 커질 수 있으므로 1234567로 나눈 나머지를 반환한다.
- F(0)=0, F(1)=1, F(n)=F(n-1)+F(n-2)를 따른다.

접근 방법
- 피보나치 수열은 이전 두 값만 있으면 다음 값을 구할 수 있다.
- 배열 대신 prev1, prev2 변수만 사용하여 값을 계산한다.
- 매 연산마다 1234567로 나눈 나머지를 저장하여 오버플로우를 방지한다.

핵심 아이디어
- current = (prev1 + prev2) % 1234567
- 이전 값들을 한 칸씩 이동하며 다음 피보나치 수를 계산한다.
- 배열을 사용하지 않아 메모리를 절약할 수 있다.

주의할 점
- 피보나치 수는 매우 빠르게 커지므로 매 단계마다 나머지 연산을 수행해야 한다.
- n이 0 또는 1인 경우를 고려하면 더욱 안전한 코드가 된다.

배운 점
- DP 문제는 반드시 배열을 사용할 필요가 없다.
- 현재 상태 계산에 필요한 값만 남겨두면 공간복잡도를 줄일 수 있다.
- 모듈러 연산을 활용하면 큰 수 계산도 안전하게 처리할 수 있다.
*/
public class No8 {
    public static void main(String[] args) {
        int n = 5;
        int answer = 0;
        int prev2 = 0;
        int prev1 = 1;


        for (int i = 2; i <= n; i++) {
            answer = (prev1 + prev2) % 1234567;
            prev2 = prev1;
            prev1 = answer;
        }

        System.out.println(answer);
    }
}

package level2;
/*
문제: 점프와 순간 이동

로직
- 목적지에서 출발점으로 거꾸로 이동한다.
- 현재 거리가 짝수이면 2로 나눈다.
- 현재 거리가 홀수이면 1을 빼고 건전지 사용량을 증가시킨다.
- 거리가 0이 될 때까지 반복한다.

핵심 구현
- n % 2로 홀수인지 확인한다.
- 짝수는 순간이동을 거꾸로 적용하여 비용 없이 처리한다.
- 홀수는 1칸 점프를 거꾸로 적용하여 비용 1을 더한다.

포인트
- 순간이동으로 도착하는 위치는 항상 짝수이다.
- 여러 칸 점프는 같은 비용의 1칸 점프 여러 번으로 나눌 수 있다.
- 거리를 절반씩 줄여 큰 입력도 빠르게 처리한다.

회고
- 출발점부터 이동하는 대신 목적지에서 거꾸로 생각했다.
- 홀수와 짝수에 따라 동작을 결정하는 그리디 방식으로 해결했다.
*/
public class No17 {
    public class Solution {
        public int solution(int n) {
            int answer = 0;

            while (n > 0) {
                if (n % 2 == 0) {
                    n /= 2;
                } else {
                    n--;
                    answer++;
                }
            }

            return answer;
        }
    }
}

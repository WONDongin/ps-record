package level2;
/*
문제: 멀리 뛰기

로직
- 각 칸에 도달하는 방법의 수를 DP 배열에 저장한다.
- 마지막에 1칸 뛰는 경우와 2칸 뛰는 경우를 더한다.
- 매 계산마다 1234567로 나눈 나머지를 저장한다.

핵심 구현
- dp[0] = 1, dp[1] = 1로 초기화한다.
- dp[i] = (dp[i - 1] + dp[i - 2]) % 1234567을 적용한다.
- dp[n]을 반환한다.

포인트
- 마지막 점프가 1칸인지 2칸인지에 따라 경우를 나눈다.
- dp[0]은 아무 점프도 하지 않은 한 가지 방법을 의미한다.
- 매 단계에서 나머지를 계산하여 정수 범위 초과를 방지한다.

회고
- 이전 두 칸의 결과로 현재 칸의 결과를 구하는 점화식을 세웠다.
- 동적 계획법으로 중복 계산 없이 해결했다.
*/
public class No16 {
    class Solution {
        public long solution(int n) {
            int[] dp = new int[n + 1];

            dp[0] = 1;
            dp[1] = 1;

            for (int i = 2; i <= n; i++) {
                dp[i] = (dp[i - 1] + dp[i - 2]) % 1234567;
            }

            return dp[n];
        }
    }
}

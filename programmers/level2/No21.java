package level2;
/*
문제: 예상 대진표

로직
- A와 B가 만나기 전까지 매 라운드 승리한다고 가정한다.
- 두 참가자의 번호를 다음 라운드 번호로 바꾸면서 라운드 수를 센다.
- 번호가 같아지면 해당 라운드에서 만난 것이므로 라운드 수를 반환한다.

핵심 구현
- (현재 번호 + 1) / 2로 다음 라운드 번호를 계산한다.
- a와 b가 다를 동안 번호 갱신과 라운드 증가를 반복한다.

포인트
- 같은 경기에서 맞붙는 두 참가자는 다음 라운드 번호가 같다.
- 전체 대진표 없이 두 참가자의 번호만으로 계산할 수 있다.
- 시간 복잡도는 O(log N), 공간 복잡도는 O(1)이다.

회고
- 다음 라운드의 번호 배정 규칙을 식으로 표현하니 구현이 간단해졌다.
*/
public class No21 {
    class Solution {
        public int solution(int n, int a, int b) {
            int round = 0;

            while (a != b) {
                a = (a + 1) / 2;
                b = (b + 1) / 2;
                round++;
            }

            return round;
        }
    }
}

package level2;

import java.util.Arrays;
/*
문제: 최솟값 만들기

문제 요약
- 배열 A와 B에서 각각 숫자를 하나씩 선택해 곱한 값을 누적한다.
- 모든 숫자를 한 번씩만 사용해야 한다.
- 누적 합이 최소가 되도록 만들어 최솟값을 반환한다.

접근 방법
- 배열 A를 오름차순 정렬한다.
- 배열 B를 오름차순 정렬한다.
- A의 작은 값과 B의 큰 값을 곱하도록 매칭한다.
- A[i]와 B[n - 1 - i]를 곱해 누적한다.

핵심 아이디어
- 가장 작은 수와 가장 큰 수를 곱해야 전체 합이 최소가 된다.
- A는 오름차순, B는 내림차순 효과가 나도록 인덱스를 반대로 접근한다.
- 정렬 후 한 번의 순회로 정답을 구할 수 있다.

주의할 점
- 같은 인덱스끼리 곱하면 최소값이 보장되지 않는다.
- B 배열을 실제로 내림차순 정렬할 필요 없이 뒤에서부터 접근해도 된다.
- 배열 길이는 최대 1,000이므로 정렬 후 처리해도 충분하다.

배운 점
- 최솟값을 만들기 위해서는 큰 수와 작은 수를 매칭하는 그리디 전략을 사용할 수 있다.
- 정렬을 활용하면 복잡한 조합 탐색 없이 최적의 결과를 얻을 수 있다.
*/
public class No6 {
    public static void main(String[] args) {
        int[] A = {1, 2};
        int[] B = {3, 4};
        int answer = 0;

        Arrays.sort(A);
        Arrays.sort(B);

        for(int i = 0; i < A.length; i++){
            answer += A[i] * B[B.length - 1 - i];
        }

        System.out.println(answer);
    }
}
